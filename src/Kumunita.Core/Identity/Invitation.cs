using Kumunita.Core.Privacy;

namespace Kumunita.Core.Identity;

/// <summary>
/// One row per email invitation (ADR 0304, IMPROVE-UX A07). A resident or
/// admin creates an invitation for one <see cref="Email"/> address: a
/// **long random token**, shown to the inviter **exactly once** at creation,
/// that opens sign-up for that address while the platform gate
/// (<see cref="IIdentityPlatformGateService.IsSignupOpenAsync"/>) is closed
/// (ADR 0304 D7 — the plan's decision).
/// <para>
/// **Hash only at rest (the ADR 0304 D2 / 0159 ESC·3 / F2 rule):**
/// <see cref="TokenHash"/> is the SHA-256 hex digest of the token. The raw
/// token is generated by <see cref="IInvitationService.CreateAsync"/>,
/// returned **once** for the caller to show, and is **never stored** — a
/// database leak yields a digest that cannot be reversed (the
/// <see cref="Kumunita.Core.Kiosk.KioskLink.TokenHash"/> and
/// <see cref="Kumunita.Core.ErrorReports.EscalationToken.TokenHash"/>
/// precedent).
/// <para>
/// The state machine: created (<see cref="Status"/> =
/// <see cref="EmailInvitationStatus.Pending"/>) → accepted
/// (<see cref="Status"/> = <see cref="EmailInvitationStatus.Accepted"/>,
/// terminal — the <see cref="IInvitationService.AcceptAsync"/> single-use
/// pin) or revoked (<see cref="Status"/> =
/// <see cref="EmailInvitationStatus.Revoked"/>, terminal). The **expired** state
/// is virtual: a <see cref="EmailInvitationStatus.Pending"/> row past
/// <see cref="ExpiresAt"/> is refused by <see cref
/// "IInvitationService.ValidateAsync"/> / <see cref
/// "IInvitationService.AcceptAsync"/> — the <see cref
/// "EmailInvitationStatus.Expired"/> enum value documents the state but is never
/// explicitly set (the <see cref="KioskLink"/> "the read is not an access
/// decision" floor).
/// </para>
/// <para>
/// The <c>[DataClass]</c> row follows the closest neighbor,
/// <see cref="Kumunita.Core.Kiosk.KioskLink"/> (an owner credential,
/// <c>Delete</c> erasure, <c>Never</c> export): the token hash is a
/// credential (the 0159 / F2 hash-at-rest rule), never exportable (a
/// sign-up credential, not the inviter's content), and erased with the
/// inviter's account — the <see cref
/// "ResidentAccountRowsEraser"/> block 15.
/// </para>
/// </summary>
[DataClass(DataClassKind.Secret, Erasure.Delete, ExportScope.Never,
    reason: "ADR 0304 (IMPROVE-UX A07): a sign-up credential (token hash, the 0159 / F2 hash-at-rest rule); never exportable (a sign-up credential, not the inviter's content); erased with the inviter's account — the ResidentAccountRowsEraser block 15 (the KioskLink credential shape)")]
public sealed class Invitation
{
    /// <summary>The document identity (Marten-generated, conventional
    /// string — the <see cref="Kumunita.Core.Kiosk
    /// .KioskLink"/> / <see cref="IdentityToken"/> / <see cref
    /// "Kumunita.Core.ErrorReports.EscalationToken"/> precedent).</summary>
    public string Id { get; set; } = default!;

    /// <summary>The invited email address (lowercased, trimmed at creation
    /// — the ADR 0304 D1 shape). The <see cref
    /// "IInvitationService.AcceptAsync"/> seam verifies the signing-up email
    /// matches this value (the token is only good for the invited address).</summary>
    public string Email { get; set; } = string.Empty;

    /// <summary>The resident or admin who created the invitation — the
    /// audit principal (ADR 0304 D3: every audit row carries
    /// <c>Via = Owner</c> with this id as the actor).</summary>
    public string InviterSubjectId { get; set; } = string.Empty;

    /// <summary>The SHA-256 hex digest of the long random token (ADR 0304
    /// D2) — **never the raw token** (the 0159 ESC·3 / F2 / ADR 0302 D2
    /// hash-at-rest rule). The raw token exists only in the
    /// <see cref="IInvitationService.CreateAsync"/> return value.</summary>
    public string TokenHash { get; set; } = string.Empty;

    /// <summary>When the invitation was created (UTC).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>The expiry instant (UTC). A <see cref
    /// "EmailInvitationStatus.Pending"/> row past this instant is refused by
    /// <see cref="IInvitationService.ValidateAsync"/> / <see cref
    /// "IInvitationService.AcceptAsync"/> (the virtual <see cref
    /// "EmailInvitationStatus.Expired"/> state — the ADR 0304 D6 open question
    /// settles the proposed default, 7 days).</summary>
    public DateTimeOffset ExpiresAt { get; set; }

    /// <summary>The state machine (see the class doc).</summary>
    public EmailInvitationStatus Status { get; set; }

    /// <summary>Set when the row moves <see cref
    /// "EmailInvitationStatus.Pending"/> → <see cref
    /// "EmailInvitationStatus.Accepted"/> (the <see cref
    /// "IInvitationService.AcceptAsync"/> single-use pin); null while
    /// Pending / Revoked. The <see cref="KioskLink.LastUsedAt"/> shape.</summary>
    public DateTimeOffset? AcceptedAt { get; set; }

    /// <summary>The subject id of the account created by the <see cref
    /// "IInvitationService.AcceptAsync"/> lane (the
    /// <see cref="IIdentityService.RegisterAsync"/> return value); null
    /// while Pending / Revoked. The <see cref
    /// "Kumunita.Core.Kiosk.KioskLink.OwnerSubjectId"/> shape — the
    /// invitee's identity is recorded for the audit trail.</summary>
    public string? AcceptedSubjectId { get; set; }
}

/// <summary>
/// The <see cref="Invitation"/> state machine (ADR 0304 D1):
/// <see cref="Pending"/> → <see cref="Accepted"/> (the
/// <see cref="IInvitationService.AcceptAsync"/> single-use pin — terminal)
/// or <see cref="Pending"/> → <see cref="Revoked"/> (the
/// <see cref="IInvitationService.RevokeAsync"/> owner-scoped no-op shape —
/// terminal). <see cref="Expired"/> is a **virtual** state: a
/// <see cref="Pending"/> row past <see cref="Invitation.ExpiresAt"/> is
/// refused by the validate/accept seams; the value is never explicitly
/// set (the ADR 0304 D6 open question settles the default expiry length).
/// </summary>
public enum EmailInvitationStatus
{
    /// <summary>Created, not yet accepted or revoked — the invitation is
    /// live (the <see cref="IInvitationService.ValidateAsync"/> seam
    /// returns the row when <see cref="Invitation.ExpiresAt"/> has not
    /// passed).</summary>
    Pending,

    /// <summary>Accepted — the <see cref
    /// "IInvitationService.AcceptAsync"/> lane ran the
    /// <see cref="IIdentityService.RegisterAsync"/> seam and marked the row
    /// done. Terminal: a second <see cref
    /// "IInvitationService.AcceptAsync"/> for the same token is refused
    /// (the single-use pin, ADR 0304 D4).</summary>
    Accepted,

    /// <summary>Revoked — the inviter (or a GlobalAdmin via A09) revoked
    /// the invitation. Terminal: the next <see cref
    /// "IInvitationService.ValidateAsync"/> refuses it (the ADR 0302 D3
    /// owner-scoped no-op shape).</summary>
    Revoked,

    /// <summary>Expired — a virtual state: a <see cref="Pending"/> row past
    /// <see cref="Invitation.ExpiresAt"/> is refused by the
    /// validate/accept seams. Never explicitly set (the ADR 0304 D6 open
    /// question settles the default expiry length; the
    /// <see cref="Invitation.ExpiresAt"/> field is the check, not this
    /// value).</summary>
    Expired
}

/// <summary>
/// The **resident-invite mode** (ADR 0304, amended 2026-11-11 for IMPROVE-UX
/// A11): the admin-settled posture for whether *residents* may invite
/// neighbours (the A12 "Invite a neighbour" surface). A 3-state code-owned
/// closed set (the <see cref="Kumunita.Core.UserInfo.EventRsvpMode"/>
/// 3-state posture shape, the <see cref="EmailInvitationStatus"/> enum
/// convention — **not** a stored string). Stored on
/// <see cref="Kumunita.Core.Localization.LocaleSettings.ResidentInviteSetting"/>
/// (the <see cref="IsSignupOpen"/> / <see cref="NotifyAdminsOnSignup"/>
/// singleton field shape, ADR 0004 §B.1 additive).
/// <para>
/// **The floor is <see cref="Off"/>**: a fresh instance ships with resident
/// self-invite *off* — resident invite is opt-in, set by a GlobalAdmin
/// (the ADR 0304 D4 "works while closed" posture; the deliberate
/// <b>inverse</b> of the codebase <c>true</c>-floor convention, like
/// <c>MessagingEnabled</c>). A missing singleton or an unset value both
/// yield <c>Off</c> (the read floor, resolved in
/// <see cref="IIdentityService.GetResidentInviteSettingAsync"/>).
/// </para>
/// </summary>
public enum ResidentInviteSetting
{
    /// <summary>
    /// The **floor** — resident self-invite is **off**: no resident may
    /// create an invitation (the A12 "Invite a neighbour" surface is
    /// hidden and its seam refuses). A fresh instance ships in this state
    /// (the ADR 0304 §Amendments A11 rule — resident invite is opt-in, set
    /// by a GlobalAdmin). The admin invitation surface
    /// (<c>/admin/invitations</c>, A09) is unaffected — GlobalAdmins
    /// always invite.
    /// </summary>
    Off,

    /// <summary>
    /// Resident self-invite is **on, immediate**: a resident's created
    /// invitations are immediately usable (the <see cref
    /// "IInvitationService.CreateAsync"/> / <see cref
    /// "IInvitationService.InviteAsync"/> lane runs without a gate). The
    /// single-use / expiring / revocable invariants (ADR 0304 D4) still
    /// apply — the mode controls *who may create*, not *what a row can
    /// do*.
    /// </summary>
    On,

    /// <summary>
    /// Resident self-invite is **on, with admin approval**: a resident's
    /// created invitations are gated behind the admin approval queue A12
    /// ships (the ADR 0304 D6 c "approval state" — the row state
    /// <c>PendingApproval</c> + the admin-approve lane land with A12;
    /// A11 settles the *mode* + the *rule*). A11's rule returns
    /// <see cref="ResidentInvitePosture.RequiresApproval"/> = <c>true</c>
    /// for this state (the A12 surface reads the flag and enforces it).
    /// </summary>
    OnWithApproval
}

/// <summary>
/// The **resident invite posture** (ADR 0304, amended 2026-11-11 for
/// IMPROVE-UX A11): the testable decision the
/// <see cref="IInvitationService.GetResidentInvitePostureAsync"/> seam
/// returns for a resident — what A12's "Invite a neighbour" surface reads
/// before calling <see cref="IInvitationService.CreateAsync"/> /
/// <see cref="IInvitationService.InviteAsync"/>.
/// <para>
/// **Pure, testable, setting-driven (A11):**
/// <list type="bullet">
/// <item><see cref="ResidentInviteSetting.Off"/> →
/// <c>MayInvite = false</c> (the A12 surface refuses).</item>
/// <item><see cref="ResidentInviteSetting.On"/> →
/// <c>MayInvite = true, RequiresApproval = false</c> (the A12 surface
/// proceeds directly).</item>
/// <item><see cref="ResidentInviteSetting.OnWithApproval"/> →
/// <c>MayInvite = true, RequiresApproval = true</c> (the A12 surface
/// proceeds but the row is gated behind the admin approval queue).</item>
/// </list>
/// The rule is a **read** — zero audit rows (the
/// <see cref="IIdentityService.IsSignupOpenAsync"/> /
/// <see cref="IInvitationService.ValidateAsync"/> "the read is not an
/// access decision" floor — the *write* decision is the A12
/// <c>CreateAsync</c> lane's job).
/// </para>
/// <para>
/// <b>// TODO ❓</b> the ADR 0304 D6 b open question — **who may invite
/// and how many per period** — is **flagged, not built** here: A11 ships
/// the *setting-driven* rule; the who-may-invite + rate-limit refinement
/// is A12's (or a follow-on), and the proposed 5-per-30-days ceiling from
/// D6 b stands. A11's rule does **not** reject on rate; A12 (or a
/// follow-on) will settle it.
/// </para>
/// </summary>
public readonly record struct ResidentInvitePosture(
    bool MayInvite,
    bool RequiresApproval)
{
    /// <summary>The <see cref="ResidentInviteSetting.Off"/> posture —
    /// the resident may not create an invitation (the A12 surface
    /// refuses, the ADR 0304 §Amendments A11 floor).</summary>
    public static readonly ResidentInvitePosture Refused = new(false, false);

    /// <summary>The <see cref="ResidentInviteSetting.On"/> posture — the
    /// resident may create an invitation, immediately usable (the A12
    /// surface proceeds directly).</summary>
    public static readonly ResidentInvitePosture Allow = new(true, false);

    /// <summary>The <see cref="ResidentInviteSetting.OnWithApproval"/>
    /// posture — the resident may create an invitation, but the row is
    /// gated behind the admin approval queue (the A12 surface proceeds
    /// but the row lands in <c>PendingApproval</c> until an admin
    /// approves, ADR 0304 D6 c).</summary>
    public static readonly ResidentInvitePosture AllowWithApproval = new(true, true);
}
