using Kumunita.Core.Privacy;

namespace Kumunita.Core.Kiosk;

/// <summary>
/// One row per shared kiosk link (ADR 0302, IMPROVE-UX R15). A resident
/// creates a link for one of their <see cref="KioskPlaylist"/> rows (the
/// per-resident playlist, ADR 0164 / 0285): a **long random token**, shown
/// to the owner **exactly once** at creation, that the R16 middleware
/// authenticates **only** on <c>/kiosk</c> + its slides — read-only,
/// community-visible items only (the denied slide otherwise), every read
/// audited under the owner (ADR 0302 D4).
/// <para>
/// **Hash only at rest (the ADR 0302 D2 / 0159 ESC·3 / F2 rule):**
/// <see cref="TokenHash"/> is the SHA-256 hex digest of the token. The raw
/// token is generated by <see cref="IKioskLinkService.CreateAsync"/>,
/// returned **once** for the caller to show, and is **never stored** — a
/// database leak yields a digest that cannot be reversed (the
/// <see cref="Kumunita.Core.ErrorReports.EscalationToken.TokenHash"/> and
/// <see cref="Kumunita.Core.Identity.IdentityToken.Token"/> precedent).
/// <para>
/// The state machine: created (<see cref="RevokedAt"/> null) → revoked
/// (<see cref="RevokedAt"/> set, terminal — the R19 SEC review settles
/// whether a max age / expiry also applies). <see cref="LastUsedAt"/> is
/// stamped on each successful <see cref="IKioskLinkService
/// .ValidateAsync"/> (a read-then-write, **no** audit row — the M35·5 /
/// 0159 ESC·9 "the read is not an access decision" floor).
/// </para>
/// </summary>
[DataClass(DataClassKind.Secret, Erasure.Delete, ExportScope.Never,
    reason: "ADR 0302 (IMPROVE-UX R15): an owner credential (token hash, the 0159 / F2 hash-at-rest rule); never exportable (a shared credential, not the resident's content); erased with the owner account — the IdentityToken / EscalationToken credential shape (the R19 SEC review confirms the eraser seam)")]
public sealed class KioskLink
{
    /// <summary>The document identity (Marten-generated, conventional
    /// string — the <see cref="Kumunita.Core.ErrorReports
    /// .EscalationToken"/> / <see cref="Kumunita.Core.Identity
    /// .IdentityToken"/> precedent).</summary>
    public string Id { get; set; } = default!;

    /// <summary>The <see cref="KioskPlaylist"/> this link plays (the
    /// playlist's <c>Id</c> = the owner's subject id, ADR 0164).</summary>
    public string PlaylistId { get; set; } = string.Empty;

    /// <summary>The resident who created the link — the audit principal
    /// (ADR 0302 D4: every read the link authenticates is audited under the
    /// owner).</summary>
    public string OwnerSubjectId { get; set; } = string.Empty;

    /// <summary>The SHA-256 hex digest of the long random token (ADR 0302
    /// D2) — **never the raw token** (the 0159 ESC·3 / F2 hash-at-rest
    /// rule). The raw token exists only in the
    /// <see cref="IKioskLinkService.CreateAsync"/> return value.</summary>
    public string TokenHash { get; set; } = string.Empty;

    /// <summary>When the link was created (UTC).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Stamped on each successful
    /// <see cref="IKioskLinkService.ValidateAsync"/> (a read-then-write, no
    /// audit row — the 0159 ESC·9 precedent); null until first use.</summary>
    public DateTimeOffset? LastUsedAt { get; set; }

    /// <summary>Set when the link is revoked (immediate — the R16 validate
    /// refuses it on the next call); null while valid. The R19 SEC review
    /// settles whether an expiry / max age also applies (ADR 0302 D6).</summary>
    public DateTimeOffset? RevokedAt { get; set; }
}
